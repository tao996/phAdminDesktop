use tauri::State;

use crate::AppState;

const ENV_TEMPLATE: &str = include_str!("../templates/env.example");

fn render_env(project: &str, remote_path: &str, nginx_port: i64) -> String {
    ENV_TEMPLATE
        .replace("{{TZ}}", "Asia/Shanghai")
        .replace("{{APP_NAME}}", project)
        .replace("{{DATA_PATH_HOST}}", remote_path)
        .replace("{{NGINX_PORT}}", &nginx_port.to_string())
        .replace("{{MYSQL_PASSWORD}}", "")
        .replace("{{MYSQL_USER}}", project)
        .replace("{{MYSQL_DATABASE}}", project)
        .replace("{{REDIS_PASSWORD}}", "")
        .replace("{{NGINX_IMAGE}}", "nginx:stable-alpine")
        .replace("{{PHP_IMAGE}}", "authus/phalcon:5.23.0")
        .replace("{{MYSQL_IMAGE}}", "mysql:8.1.0")
        .replace("{{REDIS_IMAGE}}", "redis:7.2-alpine")
}

fn render_nginx(domains: &[String], nginx_port: i64, ssl: bool) -> String {
    let server_name = domains.join(" ");
    let primary = domains.first().cloned().unwrap_or_default();
    let mut config = format!(
        r#"# Auto-generated by PhAdmin Desktop for: {server_name}
server {{
    listen 80;
    server_name {server_name};

    proxy_http_version 1.1;
    proxy_read_timeout 120;

    proxy_set_header Host $http_host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Forwarded-Port $server_port;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $http_upgrade;

    location / {{
        proxy_pass http://127.0.0.1:{nginx_port};
    }}
}}
"#
    );

    if ssl {
        config.push_str(&format!(
            r#"
server {{
    listen 443 ssl http2;
    server_name {server_name};

    ssl_certificate     /etc/nginx/ssl/{primary}.pem;
    ssl_certificate_key /etc/nginx/ssl/{primary}.key;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         HIGH:!aNULL:!MD5;

    proxy_http_version 1.1;
    proxy_read_timeout 120;

    proxy_set_header Host $http_host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Forwarded-Port $server_port;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $http_upgrade;

    location / {{
        proxy_pass http://127.0.0.1:{nginx_port};
    }}
}}
"#
        ));
    }

    config
}

#[tauri::command]
pub fn render_config_preview(
    state: State<'_, AppState>,
    deployment_id: String,
) -> Result<String, String> {
    let connection = state
        .db
        .lock()
        .map_err(|error| format!("数据库连接被占用: {error}"))?;
    let (project, remote_path, nginx_port) = connection
        .query_row(
            "SELECT p.name, d.remote_path, d.nginx_port
             FROM deployments d
             JOIN projects p ON p.id = d.project_id
             WHERE d.id = ?1",
            [&deployment_id],
            |row| {
                Ok((
                    row.get::<_, String>(0)?,
                    row.get::<_, String>(1)?,
                    row.get::<_, i64>(2)?,
                ))
            },
        )
        .map_err(|error| format!("部署不存在: {error}"))?;
    Ok(render_env(&project, &remote_path, nginx_port))
}

#[tauri::command]
pub fn render_nginx_preview(
    state: State<'_, AppState>,
    deployment_id: String,
) -> Result<String, String> {
    let connection = state
        .db
        .lock()
        .map_err(|error| format!("数据库连接被占用: {error}"))?;
    let (nginx_port, ssl, domain): (i64, i64, String) = connection
        .query_row(
            "SELECT nginx_port, ssl, domain FROM deployments WHERE id = ?1",
            [&deployment_id],
            |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
        )
        .map_err(|error| format!("部署不存在: {error}"))?;

    let mut domains = Vec::new();
    let mut statement = connection
        .prepare("SELECT domain FROM domains WHERE deployment_id = ?1 ORDER BY sort")
        .map_err(|error| format!("读取域名失败: {error}"))?;
    let rows = statement
        .query_map([&deployment_id], |row| row.get::<_, String>(0))
        .map_err(|error| format!("读取域名失败: {error}"))?;
    for row in rows {
        domains.push(row.map_err(|error| format!("读取域名失败: {error}"))?);
    }
    if domains.is_empty() && !domain.trim().is_empty() {
        domains.push(domain);
    }
    if domains.is_empty() {
        domains.push("example.com".to_string());
    }

    Ok(render_nginx(&domains, nginx_port, ssl != 0))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_env_without_placeholders() {
        let env = render_env("demo", "/data/demo", 8071);
        assert!(env.contains("APP_NAME=demo"));
        assert!(env.contains("NGINX_PORT=8071"));
        assert!(env.contains("DATA_PATH_HOST=/data/demo"));
        assert!(env.contains("PHP_IMAGE=authus/phalcon:5.23.0"));
        assert!(!env.contains("{{"));
    }

    #[test]
    fn renders_nginx_with_ssl() {
        let nginx = render_nginx(&["demo.example.com".to_string()], 8071, true);
        assert!(nginx.contains("server_name demo.example.com;"));
        assert!(nginx.contains("proxy_pass http://127.0.0.1:8071;"));
        assert!(nginx.contains("listen 443 ssl http2;"));
        assert!(nginx.contains("/etc/nginx/ssl/demo.example.com.pem"));
    }
}
